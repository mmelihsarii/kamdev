-- KAM uygulamasının PHP backend'inin kullandığı PostgreSQL şeması.
-- Supabase SQL Editor'da bir kez çalıştırın. Uygulama tabloları yalnızca
-- sunucunun SUPABASE_DB_URL bağlantısıyla kullanılır; anon/authenticated
-- istemcilerine açık tablo politikası oluşturulmaz.

begin;

create table if not exists public.ayarlar (
  anahtar text primary key,
  veri text not null,
  guncelleme text
);

create table if not exists public.ogeler (
  koleksiyon text not null check (koleksiyon in (
    'projeler', 'hizmetler', 'yazilar', 'sss', 'surec', 'ilkeler', 'teknolojiler'
  )),
  kimlik text not null,
  sira integer not null default 0,
  veri text not null,
  guncelleme text,
  primary key (koleksiyon, kimlik)
);

create table if not exists public.kullanicilar (
  id integer generated by default as identity primary key,
  eposta text not null,
  sifre text not null,
  ad text not null default '',
  firma text not null default '',
  telefon text not null default '',
  rol text not null check (rol in ('yonetici', 'musteri')),
  aktif integer not null default 1,
  olusturma text,
  son_giris text
);
create unique index if not exists kullanicilar_eposta_lower_uq
  on public.kullanicilar (lower(eposta));

create table if not exists public.musteri_projeleri (
  id integer generated by default as identity primary key,
  musteri_id integer not null references public.kullanicilar(id) on delete cascade,
  ad text not null,
  ozet text not null default '',
  asama integer not null default 0,
  ilerleme integer not null default 0,
  sorumlu text not null default '',
  teknolojiler text not null default '[]',
  onizleme text not null default '',
  canli text not null default '',
  baslangic text not null default '',
  teslim text not null default '',
  durum text not null default 'devam',
  notlar text not null default '',
  olusturma text,
  guncelleme text
);
create index if not exists musteri_projeleri_musteri_idx
  on public.musteri_projeleri (musteri_id);

create table if not exists public.proje_guncellemeleri (
  id integer generated by default as identity primary key,
  proje_id integer not null references public.musteri_projeleri(id) on delete cascade,
  tarih text not null,
  baslik text not null,
  aciklama text not null default '',
  asama integer,
  dosyalar text not null default '[]',
  olusturma text
);
create index if not exists proje_guncellemeleri_proje_tarih_idx
  on public.proje_guncellemeleri (proje_id, tarih desc, id desc);

create table if not exists public.proje_sorunlari (
  id integer generated by default as identity primary key,
  proje_id integer not null references public.musteri_projeleri(id) on delete cascade,
  tur text not null default 'sorun' check (tur in ('sorun', 'risk', 'bekleyen')),
  baslik text not null,
  aciklama text not null default '',
  durum text not null default 'acik' check (durum in ('acik', 'cozuldu')),
  olusturma text,
  guncelleme text
);
create index if not exists proje_sorunlari_proje_idx
  on public.proje_sorunlari (proje_id);

create table if not exists public.dosyalar (
  id integer generated by default as identity primary key,
  ad text not null,
  yol text not null,
  tur text not null,
  boyut integer not null default 0,
  genislik integer,
  yukseklik integer,
  ozel integer not null default 0,
  proje_id integer references public.musteri_projeleri(id) on delete set null,
  olusturma text
);
create index if not exists dosyalar_proje_idx on public.dosyalar (proje_id);

create table if not exists public.talepler (
  id integer generated by default as identity primary key,
  konu text not null default '',
  ad text not null default '',
  firma text not null default '',
  iletisim text not null default '',
  mesaj text not null default '',
  ip text not null default '',
  durum text not null default 'yeni',
  olusturma text
);
create index if not exists talepler_durum_id_idx on public.talepler (durum, id desc);

create table if not exists public.deneme_kayitlari (
  tur text not null,
  ip text not null,
  zaman bigint not null
);
create index if not exists deneme_idx on public.deneme_kayitlari (tur, ip, zaman);

create table if not exists public.cop (
  id integer generated by default as identity primary key,
  tur text not null,
  baslik text not null default '',
  veri text not null,
  silen text not null default '',
  silinme text
);

create index if not exists ogeler_sira_idx on public.ogeler (koleksiyon, sira, kimlik);

alter table public.ayarlar enable row level security;
alter table public.ogeler enable row level security;
alter table public.kullanicilar enable row level security;
alter table public.musteri_projeleri enable row level security;
alter table public.proje_guncellemeleri enable row level security;
alter table public.proje_sorunlari enable row level security;
alter table public.dosyalar enable row level security;
alter table public.talepler enable row level security;
alter table public.deneme_kayitlari enable row level security;
alter table public.cop enable row level security;

commit;
